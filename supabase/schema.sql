-- NuvioFit database schema, rebuilt from what the app reads and writes.
-- Run this once in the Supabase SQL editor of a fresh project.
--
-- Auth: users sign in with Clerk. The frontend sends a Clerk JWT (template named "supabase"),
-- so auth.jwt() ->> 'sub' is the Clerk user id (e.g. "user_2abc...") and user_id columns are text.

create table if not exists public.onboarding_responses (
  id                  bigint generated by default as identity primary key,
  user_id             text unique not null,
  created_at          timestamptz not null default now(),

  -- account / onboarding state
  username            text,
  email               text,
  quiz_completed      boolean not null default false,
  "setupFinished"     boolean not null default false,

  -- onboarding answers (GettingStarted.tsx)
  achievements        text,
  workout_history     text,
  fitness_why         text,
  other_why           text,
  future_vision       text,
  resilience_trigger  text,
  pushing_comfort     text,
  consistency_blocker text,
  custom_blocker      text,
  support_system      text,
  custom_support      text,
  what_to_imporve     text,   -- (sic) spelling used by the app
  training_method     text,
  training_frequency  text,
  training_duration   text,
  workout_level       text,
  injuries            text,
  recommedations      text,   -- (sic) spelling used by the app

  -- generated plan + usage limits
  fitness_plan        text,
  workout_count       integer not null default 0,
  messages_left       integer not null default 30,
  editplantimes       integer not null default 1,
  last_reset_at       timestamptz default now(),
  reset_at            timestamptz,

  -- weekly check-ins (analytics panel)
  cycle_start         date,
  steps               text,
  mood                text,
  energy              text,

  -- emails
  feedback_sent       boolean not null default false,
  unsubscribed        boolean not null default false
);

create table if not exists public.feedback (
  id         bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  user_id    text,
  username   text,
  email      text,
  message    text not null
);

create table if not exists public.waitlist (
  id         bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  email      text not null,
  name       text
);

create table if not exists public.waitlist_features (
  id              bigint generated by default as identity primary key,
  created_at      timestamptz not null default now(),
  user_id         text,
  username        text,
  email           text,
  nutrition       boolean default false,
  meditation      boolean default false,
  goal_tracking   boolean default false,
  smartwatch_sync boolean default false
);

-- Row level security: signed-in users only see and change their own rows.
alter table public.onboarding_responses enable row level security;
alter table public.feedback             enable row level security;
alter table public.waitlist             enable row level security;
alter table public.waitlist_features    enable row level security;

create policy "own onboarding row" on public.onboarding_responses
  for all using (user_id = auth.jwt() ->> 'sub') with check (user_id = auth.jwt() ->> 'sub');

create policy "insert own feedback" on public.feedback
  for insert with check (user_id = auth.jwt() ->> 'sub');

create policy "insert own feature votes" on public.waitlist_features
  for insert with check (user_id = auth.jwt() ->> 'sub');

-- The public waitlist form works without signing in.
create policy "anyone can join waitlist" on public.waitlist
  for insert to anon, authenticated with check (true);
